#!/usr/bin/env python3
"""Figures + results/summary.md.   python3 scripts/plot.py"""
import json
import pathlib
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from lmppi import plotstyle  # noqa: E402
from lmppi.plotstyle import SERIES, MUTED  # noqa: E402

plotstyle.apply()
import matplotlib.pyplot as plt  # noqa: E402

RES = pathlib.Path(__file__).resolve().parents[1] / "results"
ORDER = ["oracle", "greybox", "hybrid_residual", "mlp_ensemble", "rff_gp", "koopman_edmd", "nominal"]
COLOR = {"oracle": "#1f1f1e", "greybox": SERIES[0], "hybrid_residual": SERIES[2], "mlp_ensemble": SERIES[1],
         "rff_gp": SERIES[6], "koopman_edmd": SERIES[3], "nominal": "#8f8d86", "mlp_ensemble_round2": SERIES[4]}
LABEL = {"oracle": "true model (oracle)", "greybox": "grey-box physics (identified)",
         "hybrid_residual": "nominal physics + NN residual", "mlp_ensemble": "probabilistic MLP ensemble",
         "rff_gp": "GP (random Fourier features)", "koopman_edmd": "Koopman / EDMD linear predictor",
         "nominal": "nominal physics (no learning)", "mlp_ensemble_round2": "MLP ensemble + 1 round of on-policy data"}


def md(df, fmt=".3g"):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(f"{v:{fmt}}" if isinstance(v, (float, np.floating)) else str(v) for v in r) + " |")
    return "\n".join(out)


def main():
    parts = ["# Results (generated by scripts/plot.py)"]
    pr = pd.read_csv(RES / "prediction.csv")
    fig, ax = plt.subplots(figsize=(7.2, 3.8))
    for m in ORDER:
        x = pr[pr.model == m].sort_values("horizon_s")
        ax.plot(x.horizon_s, x.rmse_theta_deg, marker="o", ms=4, color=COLOR[m], label=LABEL[m],
                ls="--" if m == "oracle" else "-")
    ax.set_yscale("log")
    ax.set_xlabel("open-loop prediction horizon [s]")
    ax.set_ylabel("pole angle RMSE [deg]")
    ax.set_title("Multi-step prediction on held-out episodes")
    ax.legend(fontsize=7.5, loc="upper left")
    fig.tight_layout()
    fig.savefig(RES / "prediction.png")
    plt.close(fig)
    tab = pr.pivot(index="model", columns="horizon_s", values="rmse_theta_deg").loc[ORDER]
    tab.columns = [f"{c:.2f} s" for c in tab.columns]
    parts.append("## Pole-angle RMSE [deg] vs open-loop horizon\n\n" + md(tab.reset_index()))

    stats = json.loads((RES / "fit_stats.json").read_text())
    gb = stats["greybox"]
    true = {"mp": 0.36, "l": 0.55, "b_cart": 1.0, "fc_cart": 0.8, "b_pivot": 0.004, "tau_act": 0.10, "deadzone": 1.0}
    rows = [{"parameter": k, "true": v, "identified": gb[k], "error [%]": 100 * (gb[k] / v - 1)} for k, v in true.items()]
    parts.append("## Grey-box identification\n\n" + md(pd.DataFrame(rows)))
    parts.append("## Fit times\n\n" + md(pd.DataFrame([{"model": k, "fit [s]": v.get("fit_s", 0.0)} for k, v in stats.items()])))
    parts.append("## One-step 95% interval coverage\n\n" + md(pd.read_csv(RES / "calibration.csv")))

    c = pd.read_csv(RES / "control.csv")
    if (RES / "control_round2.csv").exists():
        c = pd.concat([c, pd.read_csv(RES / "control_round2.csv")])
    order = [m for m in ORDER + ["mlp_ensemble_round2"] if m in set(c.model)]
    g = c.groupby("model").agg(success=("success", "mean"), n=("success", "size"),
                               t_up=("t_first_upright", "median"), final_err=("final_angle_err_deg", "median"),
                               ms=("mean_ms", "mean"), p99=("p99_ms", "mean")).loc[order].reset_index()
    g["success"] = (100 * g.success).round(0)
    g.columns = ["model", "success [%]", "episodes", "median time to upright [s]", "median final angle error [deg]",
                 "mean MPPI step [ms]", "p99 MPPI step [ms]"]
    parts.append("## Closed-loop MPPI swing-up on the true plant\n\n" + md(g))

    fig, ax = plt.subplots(figsize=(7.6, 4.6))
    for m in order:
        f = RES / f"episode_{m}_0.csv"
        if not f.exists():
            continue
        d = pd.read_csv(f)
        err = np.degrees(np.abs((d.theta - np.pi + np.pi) % (2 * np.pi) - np.pi))
        ax.plot(d.t, err, color=COLOR[m], lw=1.1, label=LABEL[m], ls="--" if m == "oracle" else "-")
    ax.axhline(12, color=MUTED, lw=0.8, ls=":")
    ax.text(0.05, 14, "success band (12 deg)", fontsize=7, color=MUTED)
    ax.set_xlabel("time [s]")
    ax.set_ylabel("pole angle from upright [deg]")
    ax.set_ylim(0, 185)
    ax.set_title("MPPI swing-up on the mystery plant, seed 0")
    ax.legend(fontsize=7, loc="upper center", bbox_to_anchor=(0.5, -0.16), ncol=3, frameon=False)
    fig.tight_layout()
    fig.savefig(RES / "swingup.png")
    plt.close(fig)
    (RES / "summary.md").write_text("\n\n".join(parts) + "\n")
    print((RES / "summary.md").read_text())


if __name__ == "__main__":
    main()
